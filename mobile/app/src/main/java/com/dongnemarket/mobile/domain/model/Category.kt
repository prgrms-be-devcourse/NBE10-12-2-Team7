package com.dongnemarket.mobile.domain.model

/**
 * 상품 카테고리. 홈 화면의 카테고리 칩 하나에 대응한다.
 *
 * 서버가 주는 정보는 `id`, `name` **두 개뿐**이다(계약 §2-2, §8-8).
 * 아이콘·정렬순서·상위 카테고리 같은 필드는 백엔드에 존재하지 않으므로
 * 이 모델에도 만들지 않는다. 있는 척하는 필드는 언젠가 거짓을 표시하게 된다.
 *
 * - **아이콘**: 서버가 주지 않는다 → UI가 [name] 문자열로 앱 내부 벡터 리소스를 매핑하고,
 *   매핑에 없는 이름이면 기본 아이콘으로 폴백한다(서버가 카테고리를 추가해도 크래시하지 않게).
 * - **칩 순서**: 서버가 `id ASC`(시드 등록순: 디지털기기·생활가전·가구/인테리어·의류·도서·
 *   스포츠/레저·반려동물용품·기타)로 주므로 **클라이언트에서 재정렬하지 않는다.**
 *   Repository 가 돌려주는 리스트 순서를 그대로 그리면 된다.
 *
 * @param id 카테고리 PK. 상품 검색 시 `categoryId` 쿼리 파라미터로 넘기는 값이다.
 * @param name 화면에 그대로 노출하는 한국어 이름.
 */
data class Category(
    val id: Long,
    val name: String,
)
